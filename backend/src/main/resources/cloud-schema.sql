-- 云端演示环境使用 H2 的建表脚本（本地开发仍使用 SQL Server 的 sql/init.sql）
CREATE TABLE IF NOT EXISTS note (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_date DATE NOT NULL,
    category VARCHAR(10) NOT NULL DEFAULT '日记',
    title VARCHAR(200) NOT NULL,
    content CLOB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS todo (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    priority VARCHAR(10) NOT NULL DEFAULT '中',
    due_date DATE NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT '待办',
    note VARCHAR(300),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS timeline (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    title VARCHAR(100) NOT NULL,
    detail VARCHAR(500),
    url VARCHAR(500),
    amount DECIMAL(10,2),
    tag VARCHAR(50),
    happened_at TIMESTAMP NOT NULL,
    note_id INT,
    CONSTRAINT fk_timeline_note FOREIGN KEY (note_id) REFERENCES note(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS pomodoro (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    minutes INT NOT NULL,
    started_at TIMESTAMP NOT NULL,
    ended_at TIMESTAMP NOT NULL,
    note VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS daily_summary (
    log_date DATE PRIMARY KEY,
    mood VARCHAR(10),
    tomorrow_focus VARCHAR(200),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
